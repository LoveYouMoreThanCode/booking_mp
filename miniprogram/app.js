/* 云开发环境 ID。
   它不是秘密 —— 只是个环境的名字，真正的门在云函数的鉴权和数据库权限上。
   留空字符串则用「默认环境」（只有一个环境时够用）。 */
const CLOUD_ENV = 'cloud1-d9g6qqofq25c8cc12';

App({
  onLaunch() {
    /* 云开发要在用 wx.cloud 之前 init 一次，而且【必须在 onLaunch 里】——
       放到页面里会因为页面加载顺序而不确定。
       wx.cloud 不存在说明基础库太老（< 2.2.3），那种情况下面所有取数都会
       走到 .fail，界面停在本地缓存上，不会白屏。 */
    if (!wx.cloud) {
      console.error('基础库版本过低，用不了云开发。取数会一直失败，界面停在本地缓存。');
      return;
    }
    wx.cloud.init({ env: CLOUD_ENV, traceUser: true });
  },

  globalData: {
    // 管理端入口由长按标题触发，这里记录本次启动是否已通过口令校验。
    // 注意：这只是「防误触」，不是安全边界 —— 口令写在客户端代码里，
    // 任何人都能看到。正式版必须改成 openid 白名单 + 云函数校验。
    adminUnlocked: false,

    /* 预约页 → 填写页之间传的选择。
       选中的格子可能有几十个，塞 URL 不现实，所以放这儿过一手。
       填写页提交成功后清空，免得返回再进去重复提交。 */
    pending: null,
  },

  /* ── onLaunch 里【只】做 wx.cloud.init，不许再往里加东西 ──────
     它原来会自动灌 13 条演示订单（core 里那个 seedDemo* 函数），
     靠一个「本机已灌过」的标记防重复。删掉的原因有两条：

     1. 那个标记是按【设备】的。接云开发之后它不存在，于是每个新客人
        第一次打开小程序，都会往大家共用的数据库里灌 13 条假订单。
     2. 假订单会一直留在库里，而且分不清哪些是真的。

     代价说清楚：全新安装打开是【空表格】，没有假名字可以看。要看效果就
     自己点几单 —— 这比一屏假手机号诚实，上线前也正好用订单页走一遍
     「客人提交 → 老板确认 → 拨号」。

     演示数据没消失，搬去了 test/smoke.js：测试需要「一张有数据的表格」
     来验冲突剔除和状态流转。那是测试的 fixture，不是产品行为。

     ⚠️ smoke.js 末尾有一条静态断言盯着这个文件：不许再出现那个函数名。
        所以下面这段注释里我没写出它的全名 —— 写了就会让断言变红。 */
});
